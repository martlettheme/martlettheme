import {mkdir,writeFile} from 'node:fs/promises';
import {join} from 'node:path';
import {themes,heritage,design} from '../src/palettes.mjs';
import {terminal,vscode} from '../src/ports.mjs';
const outputs=['artifacts','site/public/downloads'];
const banner='/* Generated from src/palettes.mjs. Do not edit this file directly. */\n';
const rule=t=>'[data-martlet="'+t.mode+'"] {\n  color-scheme: '+t.mode+';\n'+Object.entries(t.tokens).map(([k,v])=>'  --martlet-'+k+': '+v.toLowerCase()+';').join('\n')+'\n}\n';
const modes=Object.values(themes);
for(const dir of outputs){
 await mkdir(dir,{recursive:true});
 const save=(name,s)=>writeFile(join(dir,name),s,'utf8');
 await Promise.all([
  save('martlet.css',banner+modes.map(rule).join('\n')),
  save('martlet.json',JSON.stringify({name:'Martlet',version:'0.1.0-dev',heritage,design,themes},null,2)+'\n'),
  ...modes.flatMap(t=>[
    save(t.id+'.css',banner+rule(t)),
    save(t.id+'.json',JSON.stringify(t,null,2)+'\n'),
    save(t.id+'-terminal.json',JSON.stringify(terminal(t),null,2)+'\n'),
    save(t.id+'-vscode.json',JSON.stringify(vscode(t),null,2)+'\n')])
 ]);
}
console.log('Generated CSS, JSON, 16-color terminal and VS Code theme files.');
